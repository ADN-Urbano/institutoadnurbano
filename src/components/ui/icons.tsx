/** Icono según formato de recurso. */
export function FormatIcon({ format, ...props }: { format: string } & SVGProps<SVGSVGElement>) {
  switch (format) {
    case "Píldora":
      return <PlayIcon {...props} />;
    case "Caso":
      return <LayersIcon {...props} />;
    case "Podcast":
      return <MicIcon {...props} />;
    default:
      return <FileIcon {...props} />;
  }
}
